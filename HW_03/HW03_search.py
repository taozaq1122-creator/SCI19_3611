# 10. A*-Search: f(n) = g(n) + h(n)
def astar_search(graph, start, goal):
    return best_first_graph_search(graph, start, goal, f=lambda n: n.cost + heuristic(n.state))


# 11. Recursive Best First Search
def recursive_best_first_search(graph, start, goal):
    expanded = 0

    def rbfs(node, f_node, f_limit):
        nonlocal expanded
        expanded += 1
        if node.state == goal:
            return node, 0
        successors = node.expand(graph)
        if not successors:
            return None, math.inf
        f_values = {}
        for child in successors:
            f_values[child.state] = max(child.cost + heuristic(child.state), f_node)

        while True:
            successors.sort(key=lambda n: f_values[n.state])
            best = successors[0]
            if f_values[best.state] > f_limit:
                return None, f_values[best.state]
            alternative = f_values[successors[1].state] if len(successors) > 1 else math.inf
            result, best_f = rbfs(best, f_values[best.state], min(f_limit, alternative))
            f_values[best.state] = best_f
            if result is not None:
                return result, best_f

    start_node = Node(start)
    result, _ = rbfs(start_node, heuristic(start), math.inf)
    return result, expanded


