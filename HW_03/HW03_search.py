def heuristic(city, goal=GOAL):
    """straight-line distance heuristic ไปยัง goal"""
    (x1, y1), (x2, y2) = locations[city], locations[goal]
    return math.hypot(x1 - x2, y1 - y2)


class Node:
    __slots__ = ('state', 'parent', 'cost', 'depth')

    def __init__(self, state, parent=None, cost=0, depth=0):
        self.state = state
        self.parent = parent
        self.cost = cost
        self.depth = depth

    def path(self):
        node, result = self, []
        while node:
            result.append(node.state)
            node = node.parent
        return list(reversed(result))

    def expand(self, graph):
        children = []
        for neighbor, dist in graph.get(self.state, {}).items():
            children.append(Node(neighbor, self, self.cost + dist, self.depth + 1))
        return children


